begin;
do $$
declare
  usuario public.perfis%rowtype;
  master_user public.perfis%rowtype;
  conversa uuid := gen_random_uuid();
  request_id uuid := gen_random_uuid();
  primeira bigint;
  resposta bigint;
  feed jsonb;
  negado boolean;
begin
  select * into strict usuario from public.perfis where role<>'bdl_admin' and prefeitura_id is not null and ativo is distinct from false limit 1;
  select * into strict master_user from public.perfis where role='bdl_admin' and ativo is distinct from false limit 1;
  primeira := public.suporte_enviar(usuario.id,false,usuario.prefeitura_id,conversa,request_id,'Teste transacional','Preciso de ajuda','[]','/frotas/veiculos');
  if primeira<>public.suporte_enviar(usuario.id,false,usuario.prefeitura_id,conversa,request_id,'Teste transacional','Preciso de ajuda','[]','/frotas/veiculos') then raise exception 'Idempotency failed'; end if;
  if (select count(*) from public.suporte_mensagens where conversa_id=conversa)<>1 then raise exception 'Duplicate message'; end if;
  feed:=public.suporte_listar(master_user.id,true);
  if not exists(select 1 from jsonb_array_elements(feed->'items') t where t->>'id'=conversa::text and (t->>'novas')::int=1) then raise exception 'Master unread missing'; end if;
  feed:=public.suporte_listar(usuario.id,false,usuario.prefeitura_id);
  if not exists(select 1 from jsonb_array_elements(feed->'items') t where t->>'id'=conversa::text and (t->>'novas')::int=0) then raise exception 'Own message unread'; end if;
  if jsonb_array_length(public.suporte_listar(usuario.id,true)->'items')<>0 then raise exception 'Forged master access'; end if;
  if jsonb_array_length(public.suporte_listar(master_user.id,false,usuario.prefeitura_id)->'items')<>0 then raise exception 'Another user sees ticket in requester mode'; end if;
  negado:=false;
  begin perform public.suporte_enviar(usuario.id,true,null,conversa,gen_random_uuid(),'Teste transacional','Ataque','[]','/'); exception when others then negado:=true; end;
  if not negado then raise exception 'Forged role could send'; end if;
  negado:=false;
  begin perform public.suporte_enviar(master_user.id,false,usuario.prefeitura_id,conversa,gen_random_uuid(),'Teste transacional','Ataque','[]','/'); exception when others then negado:=true; end;
  if not negado then raise exception 'Other requester could send'; end if;
  resposta:=public.suporte_enviar(master_user.id,true,null,conversa,gen_random_uuid(),'Teste transacional','Resposta do suporte','[]','/');
  if (select status from public.suporte_conversas where id=conversa)<>'active' then raise exception 'Reply should activate ticket'; end if;
  if not exists(select 1 from public.frota_notificacoes where suporte_id=conversa and destinatario_id=usuario.id and autor_id=master_user.id) then raise exception 'Notification recipient incorrect'; end if;
  feed:=public.listar_frota_notificacoes(usuario.prefeitura_id,master_user.id,null,array['suporte']);
  if exists(select 1 from jsonb_array_elements(feed->'items') n where n->>'suporte_id'=conversa::text) then raise exception 'Private support notification exposed'; end if;
  perform public.suporte_ler(usuario.id,false,usuario.prefeitura_id,conversa,resposta);
  perform public.suporte_ler(usuario.id,false,usuario.prefeitura_id,conversa,primeira);
  if (select ultima_id from public.suporte_leituras where conversa_id=conversa and usuario_id=usuario.id)<>resposta then raise exception 'Read receipt regressed'; end if;
  negado:=false;
  begin perform public.suporte_status(usuario.id,false,usuario.prefeitura_id,conversa,'resolved'); exception when others then negado:=true; end;
  if not negado then raise exception 'Requester resolved ticket'; end if;
  perform public.suporte_status(master_user.id,true,null,conversa,'resolved');
  negado:=false;
  begin perform public.suporte_enviar(usuario.id,false,usuario.prefeitura_id,conversa,gen_random_uuid(),'Teste transacional','Resposta','[]','/'); exception when others then negado:=true; end;
  if not negado then raise exception 'Resolved ticket accepted message'; end if;
  perform public.suporte_status(usuario.id,false,usuario.prefeitura_id,conversa,'waiting');
  perform public.suporte_enviar(usuario.id,false,usuario.prefeitura_id,conversa,gen_random_uuid(),'Teste transacional','Voltei','[]','/');
  if (select status from public.suporte_conversas where id=conversa)<>'waiting' then raise exception 'Reopen failed'; end if;
  if has_function_privilege('authenticated','public.suporte_enviar(uuid,boolean,uuid,uuid,uuid,text,text,jsonb,text)','EXECUTE') then raise exception 'RPC publicly executable'; end if;
  if has_table_privilege('authenticated','public.suporte_mensagens','SELECT') then raise exception 'Messages publicly readable'; end if;
  -- Exercise the state left by ON DELETE SET NULL without deleting real profiles.
  update public.suporte_conversas set usuario_id=null where id=conversa;
  update public.suporte_mensagens set autor_id=null where conversa_id=conversa and autor_id=usuario.id;
  feed:=public.suporte_listar(master_user.id,true);
  if not exists(select 1 from jsonb_array_elements(feed->'items') t where t->>'id'=conversa::text and t->>'usuario'=usuario.nome) then raise exception 'Deleted-user history lost'; end if;
  negado:=false;
  begin perform public.suporte_enviar(usuario.id,false,usuario.prefeitura_id,conversa,gen_random_uuid(),'Teste transacional','Ataque','[]','/'); exception when others then negado:=true; end;
  if not negado then raise exception 'Orphaned conversation claimed'; end if;
end;
$$;
rollback;
select 'PASS: creation, idempotency, master-only access, owner isolation, private notifications, read receipts, resolution/reopening, server-only access; all fixtures rolled back' as result;
